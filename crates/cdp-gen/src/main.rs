//! Generates `crates/nodriver-cdp/src/generated/` from `crates/nodriver-cdp/protocol/*.json`.
//!
//! Usage (workspace root): `cargo run -p cdp-gen && cargo fmt -p nodriver-cdp`.
//!
//! Only the domains in `DOMAINS` and the domains they reference (cross-domain `$ref`) are
//! generated. Spec fixes, the same ones as nodriver's `generate_cdp.py`, live in `fix_spec`.

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use serde::Deserialize;

const DOMAINS: &[&str] = &[
    "Browser",
    "Target",
    "Page",
    "Runtime",
    "DOM",
    "Input",
    "Network",
    "Emulation",
    "Fetch",
    "Storage",
    "Security",
    "Log",
    "IO",
    "DOMStorage",
];

#[derive(Deserialize)]
struct Protocol {
    domains: Vec<Domain>,
}

#[derive(Deserialize, Clone)]
struct Domain {
    domain: String,
    description: Option<String>,
    #[serde(default)]
    experimental: bool,
    #[serde(default)]
    deprecated: bool,
    #[serde(default)]
    types: Vec<TypeDef>,
    #[serde(default)]
    commands: Vec<CommandDef>,
    #[serde(default)]
    events: Vec<EventDef>,
}

#[derive(Deserialize, Clone)]
struct TypeDef {
    id: String,
    description: Option<String>,
    #[serde(rename = "type")]
    ty: String,
    properties: Option<Vec<Prop>>,
    #[serde(rename = "enum")]
    enum_: Option<Vec<String>>,
    items: Option<Box<Items>>,
    #[serde(default)]
    experimental: bool,
    #[serde(default)]
    deprecated: bool,
}

#[derive(Deserialize, Clone)]
struct Prop {
    name: String,
    description: Option<String>,
    #[serde(default)]
    optional: bool,
    #[serde(rename = "type")]
    ty: Option<String>,
    #[serde(rename = "$ref")]
    r#ref: Option<String>,
    items: Option<Box<Items>>,
    #[serde(rename = "enum")]
    enum_: Option<Vec<String>>,
    #[serde(default)]
    experimental: bool,
    #[serde(default)]
    deprecated: bool,
}

#[derive(Deserialize, Clone)]
struct Items {
    #[serde(rename = "type")]
    ty: Option<String>,
    #[serde(rename = "$ref")]
    r#ref: Option<String>,
}

#[derive(Deserialize, Clone)]
struct CommandDef {
    name: String,
    description: Option<String>,
    #[serde(default)]
    parameters: Vec<Prop>,
    #[serde(default)]
    returns: Vec<Prop>,
    #[serde(default)]
    experimental: bool,
    #[serde(default)]
    deprecated: bool,
}

#[derive(Deserialize, Clone)]
struct EventDef {
    name: String,
    description: Option<String>,
    #[serde(default)]
    parameters: Vec<Prop>,
    #[serde(default)]
    experimental: bool,
    #[serde(default)]
    deprecated: bool,
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../nodriver-cdp");
    let mut domains = Vec::new();
    let mut version = String::new();
    for name in ["browser_protocol.json", "js_protocol.json"] {
        let path = root.join("protocol").join(name);
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let v: serde_json::Value = serde_json::from_str(&text).unwrap();
        if name == "browser_protocol.json" {
            version = format!(
                "{}.{}",
                v["version"]["major"].as_str().unwrap_or("?"),
                v["version"]["minor"].as_str().unwrap_or("?")
            );
        }
        let p: Protocol = serde_json::from_value(v).unwrap();
        domains.extend(p.domains);
    }
    fix_spec(&mut domains);

    let selected = closure(&domains);
    let out = root.join("src/generated");
    if out.exists() {
        fs::remove_dir_all(&out).unwrap();
    }
    fs::create_dir_all(&out).unwrap();

    let mut mod_rs = String::new();
    writeln!(
        mod_rs,
        "// @generated by cdp-gen from CDP protocol {version}. Do not edit."
    )
    .unwrap();
    for d in domains.iter().filter(|d| selected.contains(&d.domain)) {
        let module = snake(&d.domain);
        writeln!(mod_rs, "pub mod {module};").unwrap();
        let code = Generator::new(d).generate(&version);
        fs::write(out.join(format!("{module}.rs")), code).unwrap();
    }
    fs::write(out.join("mod.rs"), mod_rs).unwrap();
    println!(
        "generated {} domains in {}: {}",
        selected.len(),
        out.display(),
        selected.iter().cloned().collect::<Vec<_>>().join(" ")
    );
}

/// Same fixes as nodriver's `generate_cdp.py` (`fix_protocol_spec`).
fn fix_spec(domains: &mut [Domain]) {
    for d in domains.iter_mut() {
        match d.domain.as_str() {
            "DOM" => {
                if let Some(c) = d.commands.iter_mut().find(|c| c.name == "resolveNode")
                    && let Some(p) = c.parameters.get_mut(1)
                    && p.r#ref.as_deref().is_some_and(|r| r.ends_with("BackendNodeId"))
                {
                    p.r#ref = Some("BackendNodeId".into());
                }
            }
            "Network" => {
                if let Some(t) = d.types.iter_mut().find(|t| t.id == "Cookie")
                    && let Some(p) = t
                        .properties
                        .as_mut()
                        .and_then(|ps| ps.iter_mut().find(|p| p.name == "expires"))
                {
                    p.optional = true;
                }
            }
            _ => {}
        }
    }
}

/// Requested domains plus every domain they reference, recursively.
fn closure(domains: &[Domain]) -> BTreeSet<String> {
    let by_name: BTreeMap<&str, &Domain> = domains.iter().map(|d| (d.domain.as_str(), d)).collect();
    let mut done = BTreeSet::new();
    let mut queue: Vec<String> = DOMAINS.iter().map(|s| s.to_string()).collect();
    while let Some(name) = queue.pop() {
        if !done.insert(name.clone()) {
            continue;
        }
        let d = by_name
            .get(name.as_str())
            .unwrap_or_else(|| panic!("domain {name} is not in the protocol"));
        let mut refs = Vec::new();
        for t in &d.types {
            for p in t.properties.iter().flatten() {
                collect_refs(p.r#ref.as_deref(), p.items.as_deref(), &mut refs);
            }
            collect_refs(None, t.items.as_deref(), &mut refs);
        }
        for c in &d.commands {
            for p in c.parameters.iter().chain(&c.returns) {
                collect_refs(p.r#ref.as_deref(), p.items.as_deref(), &mut refs);
            }
        }
        for e in &d.events {
            for p in &e.parameters {
                collect_refs(p.r#ref.as_deref(), p.items.as_deref(), &mut refs);
            }
        }
        for r in refs {
            if let Some((dom, _)) = r.split_once('.')
                && !done.contains(dom)
            {
                queue.push(dom.to_string());
            }
        }
    }
    done
}

fn collect_refs(r: Option<&str>, items: Option<&Items>, out: &mut Vec<String>) {
    if let Some(r) = r {
        out.push(r.to_string());
    }
    if let Some(r) = items.and_then(|i| i.r#ref.as_deref()) {
        out.push(r.to_string());
    }
}

struct Generator<'a> {
    d: &'a Domain,
    /// Names already taken in the module (protocol types + generated structs/enums).
    used: HashSet<String>,
    /// Object types of the domain (need `Box` when they reference themselves).
    objects: HashSet<String>,
    /// Inline enums emitted while generating fields, appended at the end of the module.
    extras: String,
    /// Inline enum already generated for (owner, field).
    inline: HashMap<(String, String), String>,
}

impl<'a> Generator<'a> {
    fn new(d: &'a Domain) -> Self {
        let used = d.types.iter().map(|t| t.id.clone()).collect();
        let objects = d
            .types
            .iter()
            .filter(|t| t.ty == "object" && t.properties.is_some())
            .map(|t| t.id.clone())
            .collect();
        Self {
            d,
            used,
            objects,
            extras: String::new(),
            inline: HashMap::new(),
        }
    }

    fn generate(mut self, version: &str) -> String {
        let d = self.d;
        let mut o = String::new();
        writeln!(
            o,
            "// @generated by cdp-gen from CDP protocol {version}. Do not edit."
        )
        .unwrap();
        doc_mod(&mut o, d.description.as_deref(), d.experimental, d.deprecated);
        writeln!(o, "#![allow(clippy::all, unused_imports, non_camel_case_types)]").unwrap();
        writeln!(o, "use serde::{{Deserialize, Serialize}};").unwrap();
        writeln!(o, "use crate::{{Command, Event}};\n").unwrap();

        for t in &d.types {
            self.type_def(&mut o, t);
        }
        for c in &d.commands {
            self.command(&mut o, c);
        }
        for e in &d.events {
            self.event(&mut o, e);
        }
        o.push_str(&self.extras);
        o
    }

    fn free_name(&mut self, base: String) -> String {
        let mut name = base.clone();
        let mut i = 2;
        while self.used.contains(&name) {
            name = format!("{base}{i}");
            i += 1;
        }
        self.used.insert(name.clone());
        name
    }

    fn type_def(&mut self, o: &mut String, t: &TypeDef) {
        doc(o, t.description.as_deref(), t.experimental, t.deprecated);
        if let Some(values) = &t.enum_ {
            write_enum(o, &t.id, values);
            return;
        }
        match (t.ty.as_str(), &t.properties) {
            ("object", Some(props)) => {
                let props = props.clone();
                writeln!(o, "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]").unwrap();
                writeln!(o, "pub struct {} {{", t.id).unwrap();
                for p in &props {
                    self.field(o, p, &t.id);
                }
                writeln!(o, "}}\n").unwrap();
            }
            (ty, _) => {
                let rs = self.primitive(ty, t.items.as_deref());
                writeln!(o, "pub type {} = {rs};\n", t.id).unwrap();
            }
        }
    }

    fn command(&mut self, o: &mut String, c: &CommandDef) {
        let base = pascal(&c.name);
        let params = self.free_name(format!("{base}Params"));
        let returns = if c.returns.is_empty() {
            None
        } else {
            Some(self.free_name(format!("{base}Returns")))
        };
        let method = format!("{}.{}", self.d.domain, c.name);

        doc(o, c.description.as_deref(), c.experimental, c.deprecated);
        writeln!(o, "///\n/// CDP method: `{method}`").unwrap();
        if c.parameters.iter().all(|p| p.optional) {
            writeln!(
                o,
                "#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]"
            )
            .unwrap();
        } else {
            writeln!(o, "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]").unwrap();
        }
        writeln!(o, "pub struct {params} {{").unwrap();
        for p in &c.parameters {
            self.field(o, p, &base);
        }
        writeln!(o, "}}\n").unwrap();

        // Constructor taking the required parameters, in protocol order.
        let mut args = Vec::new();
        let mut inits = Vec::new();
        for p in &c.parameters {
            let f = field_ident(&p.name);
            if p.optional {
                inits.push(format!("{f}: None"));
            } else {
                let ty = self.field_type(p, &base);
                if ty == "String" {
                    args.push(format!("{f}: impl Into<String>"));
                    inits.push(format!("{f}: {f}.into()"));
                } else {
                    args.push(format!("{f}: {ty}"));
                    inits.push(f.clone());
                }
            }
        }
        writeln!(o, "impl {params} {{").unwrap();
        writeln!(o, "    pub fn new({}) -> Self {{", args.join(", ")).unwrap();
        writeln!(o, "        Self {{ {} }}", inits.join(", ")).unwrap();
        writeln!(o, "    }}\n}}\n").unwrap();

        let ret_ty = match &returns {
            Some(r) => {
                writeln!(o, "/// Result of `{method}`.").unwrap();
                writeln!(o, "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]").unwrap();
                writeln!(o, "pub struct {r} {{").unwrap();
                for p in &c.returns {
                    self.field(o, p, &base);
                }
                writeln!(o, "}}\n").unwrap();
                r.clone()
            }
            None => "crate::Empty".to_string(),
        };
        writeln!(o, "impl Command for {params} {{").unwrap();
        writeln!(o, "    const METHOD: &'static str = \"{method}\";").unwrap();
        writeln!(o, "    type Returns = {ret_ty};").unwrap();
        writeln!(o, "}}\n").unwrap();
    }

    fn event(&mut self, o: &mut String, e: &EventDef) {
        let base = pascal(&e.name);
        let name = self.free_name(format!("{base}Event"));
        let method = format!("{}.{}", self.d.domain, e.name);
        doc(o, e.description.as_deref(), e.experimental, e.deprecated);
        writeln!(o, "///\n/// CDP event: `{method}`").unwrap();
        writeln!(o, "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]").unwrap();
        writeln!(o, "pub struct {name} {{").unwrap();
        for p in &e.parameters {
            self.field(o, p, &base);
        }
        writeln!(o, "}}\n").unwrap();
        writeln!(o, "impl Event for {name} {{").unwrap();
        writeln!(o, "    const METHOD: &'static str = \"{method}\";").unwrap();
        writeln!(o, "}}\n").unwrap();
    }

    fn field(&mut self, o: &mut String, p: &Prop, owner: &str) {
        doc_field(o, p.description.as_deref(), p.experimental, p.deprecated);
        let f = field_ident(&p.name);
        // serde strips the `r#` prefix; any other difference needs an explicit rename.
        let serde_name = f.trim_start_matches("r#");
        let ty = self.field_type(p, owner);
        let mut attrs = Vec::new();
        if serde_name != p.name {
            attrs.push(format!("rename = \"{}\"", p.name));
        }
        if p.optional {
            attrs.push("default".into());
            attrs.push("skip_serializing_if = \"Option::is_none\"".into());
        }
        if !attrs.is_empty() {
            writeln!(o, "    #[serde({})]", attrs.join(", ")).unwrap();
        }
        if p.optional {
            writeln!(o, "    pub {f}: Option<{ty}>,").unwrap();
        } else {
            writeln!(o, "    pub {f}: {ty},").unwrap();
        }
    }

    /// Rust type of a field, without the `Option` wrapper.
    fn field_type(&mut self, p: &Prop, owner: &str) -> String {
        if let Some(r) = &p.r#ref {
            let path = self.ref_path(r);
            // Direct self-reference (e.g. DOM.Node.contentDocument) needs a Box.
            if !r.contains('.') && r == owner && self.objects.contains(r) {
                return format!("Box<{path}>");
            }
            return path;
        }
        let ty = p.ty.as_deref().unwrap_or("any");
        if ty == "string"
            && let Some(values) = &p.enum_
        {
            let key = (owner.to_string(), p.name.clone());
            if let Some(n) = self.inline.get(&key) {
                return n.clone();
            }
            let name = self.free_name(format!("{owner}{}", pascal(&p.name)));
            let mut e = String::new();
            writeln!(e, "/// Values of `{}` in `{}`.", p.name, owner).unwrap();
            write_enum(&mut e, &name, values);
            self.extras.push_str(&e);
            self.inline.insert(key, name.clone());
            return name;
        }
        self.primitive(ty, p.items.as_deref())
    }

    fn primitive(&self, ty: &str, items: Option<&Items>) -> String {
        match ty {
            "string" => "String".into(),
            "integer" => "i64".into(),
            "number" => "f64".into(),
            "boolean" => "bool".into(),
            "object" => "serde_json::Map<String, serde_json::Value>".into(),
            "array" => {
                let inner = match items {
                    Some(Items { r#ref: Some(r), .. }) => self.ref_path(r),
                    Some(Items { ty: Some(t), .. }) => self.primitive(t, None),
                    _ => "serde_json::Value".into(),
                };
                format!("Vec<{inner}>")
            }
            _ => "serde_json::Value".into(),
        }
    }

    fn ref_path(&self, r: &str) -> String {
        match r.split_once('.') {
            Some((dom, t)) if dom != self.d.domain => format!("super::{}::{t}", snake(dom)),
            Some((_, t)) => t.to_string(),
            None => r.to_string(),
        }
    }
}

fn write_enum(o: &mut String, name: &str, values: &[String]) {
    writeln!(
        o,
        "#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]"
    )
    .unwrap();
    writeln!(o, "pub enum {name} {{").unwrap();
    let mut seen = HashSet::new();
    for v in values {
        let mut var = variant(v);
        while !seen.insert(var.clone()) {
            var.push('_');
        }
        writeln!(
            o,
            "    #[serde(rename = \"{}\")]",
            v.replace('\\', "\\\\").replace('"', "\\\"")
        )
        .unwrap();
        writeln!(o, "    {var},").unwrap();
    }
    let mut other = "Unrecognized".to_string();
    while seen.contains(&other) {
        other.push('_');
    }
    writeln!(
        o,
        "    /// Value not present in the protocol version used for generation."
    )
    .unwrap();
    writeln!(o, "    #[serde(other)]").unwrap();
    writeln!(o, "    {other},").unwrap();
    writeln!(o, "}}\n").unwrap();
}

fn variant(v: &str) -> String {
    let mut s = String::new();
    for part in v
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
    {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            s.extend(c.to_uppercase());
            s.push_str(cs.as_str());
        }
    }
    if s.is_empty() {
        s = "Empty".into();
    }
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, 'V');
    }
    s
}

fn pascal(s: &str) -> String {
    let mut cs = s.chars();
    match cs.next() {
        Some(c) => c.to_uppercase().collect::<String>() + cs.as_str(),
        None => String::new(),
    }
}

fn snake(s: &str) -> String {
    let cs: Vec<char> = s.chars().collect();
    let mut o = String::new();
    for (i, &c) in cs.iter().enumerate() {
        if c.is_ascii_uppercase() {
            let prev = if i > 0 { Some(cs[i - 1]) } else { None };
            let next = cs.get(i + 1).copied();
            let split = match prev {
                Some(a) if a.is_ascii_lowercase() || a.is_ascii_digit() => true,
                Some(a) if a.is_ascii_uppercase() => next.is_some_and(|p| p.is_ascii_lowercase()),
                _ => false,
            };
            if split && !o.ends_with('_') {
                o.push('_');
            }
            o.push(c.to_ascii_lowercase());
        } else if c == '-' {
            o.push('_');
        } else {
            o.push(c);
        }
    }
    o
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait",
    "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box",
    "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn field_ident(name: &str) -> String {
    let s = snake(name);
    match s.as_str() {
        "self" | "super" | "crate" | "Self" => format!("{s}_"),
        _ if KEYWORDS.contains(&s.as_str()) => format!("r#{s}"),
        _ => s,
    }
}

fn doc_lines(text: &str) -> impl Iterator<Item = String> + '_ {
    text.lines().map(|l| l.trim_end().replace("```", "'''"))
}

fn doc(o: &mut String, desc: Option<&str>, exp: bool, dep: bool) {
    write_doc(o, "///", desc, exp, dep);
}

fn doc_field(o: &mut String, desc: Option<&str>, exp: bool, dep: bool) {
    write_doc(o, "    ///", desc, exp, dep);
}

fn doc_mod(o: &mut String, desc: Option<&str>, exp: bool, dep: bool) {
    write_doc(o, "//!", desc, exp, dep);
}

fn write_doc(o: &mut String, prefix: &str, desc: Option<&str>, exp: bool, dep: bool) {
    if let Some(d) = desc {
        for l in doc_lines(d) {
            writeln!(o, "{prefix} {l}").unwrap();
        }
    }
    if (exp || dep) && desc.is_some() {
        writeln!(o, "{prefix}").unwrap();
    }
    if exp {
        writeln!(o, "{prefix} **Experimental.**").unwrap();
    }
    if dep {
        writeln!(o, "{prefix} **Deprecated.**").unwrap();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn snake_case() {
        assert_eq!(snake("documentURL"), "document_url");
        assert_eq!(snake("XMLHttpRequest"), "xml_http_request");
        assert_eq!(snake("frameId"), "frame_id");
        assert_eq!(snake("DOM"), "dom");
        assert_eq!(snake("DOMStorage"), "dom_storage");
        assert_eq!(snake("IndexedDB"), "indexed_db");
        assert_eq!(snake("IO"), "io");
        assert_eq!(snake("x"), "x");
    }

    #[test]
    fn variants() {
        assert_eq!(variant("mousePressed"), "MousePressed");
        assert_eq!(variant("no-referrer-when-downgrade"), "NoReferrerWhenDowngrade");
        assert_eq!(variant("XMLHttpRequest"), "XMLHttpRequest");
        assert_eq!(variant("1"), "V1");
        assert_eq!(variant(""), "Empty");
    }

    #[test]
    fn idents() {
        assert_eq!(field_ident("type"), "r#type");
        assert_eq!(field_ident("self"), "self_");
        assert_eq!(field_ident("objectId"), "object_id");
    }
}
